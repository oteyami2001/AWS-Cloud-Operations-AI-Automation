#!/usr/bin/env python3
"""Offline end-to-end incident simulation (NO AWS account needed, NOTHING is deployed).

Runs the real analyzer / remediation / status code against moto-mocked DynamoDB, with recorded
evidence for each demo scenario and a fake SSM client. Produces a transcript that is clearly
labelled LOCAL SIMULATION for docs/evidence/local/.

    python scripts/local_demo.py > docs/evidence/local/incident-simulation.md
"""

from __future__ import annotations

import copy
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
os.environ.setdefault("AWS_DEFAULT_REGION", "us-east-1")
os.environ["AIOPS_DISABLE_EMF"] = "1"
os.environ.setdefault("AWS_ACCESS_KEY_ID", "local-demo")
os.environ.setdefault("AWS_SECRET_ACCESS_KEY", "local-demo")

import boto3  # noqa: E402
from moto import mock_aws  # noqa: E402

from aiops.handlers.analyzer import AnalyzerService  # noqa: E402
from aiops.handlers.dashboard import render  # noqa: E402
from aiops.handlers.remediation import RemediationService  # noqa: E402
from aiops.handlers.status import StatusService  # noqa: E402
from aiops.platform import Config  # noqa: E402
from aiops.store import IncidentStore  # noqa: E402

FIX = ROOT / "tests" / "fixtures"
OPERATOR = "arn:aws:sts::123456789012:assumed-role/aiops-dev-operator/demo-operator"


class RecordedEvidence:
    def __init__(self, evidence: dict):
        self.evidence = evidence

    def collect(self, signal):
        return {"signal": {"name": signal.name, "state": signal.state}, **copy.deepcopy(self.evidence)}


class Quiet:
    def publish(self, subject, body):
        print(f"> SNS notification: **{subject}**")


class FakeSSM:
    n = 0

    def start_automation_execution(self, **kw):
        FakeSSM.n += 1
        print(f"> SSM StartAutomationExecution `{kw['DocumentName']}` params={json.dumps(kw['Parameters'])}")
        return {"AutomationExecutionId": f"exec-local-{FakeSSM.n}"}


def make_table():
    ddb = boto3.resource("dynamodb", region_name="us-east-1")
    return ddb.create_table(
        TableName="aiops-dev-incidents",
        BillingMode="PAY_PER_REQUEST",
        KeySchema=[{"AttributeName": "incident_id", "KeyType": "HASH"}],
        AttributeDefinitions=[
            {"AttributeName": a, "AttributeType": "S"}
            for a in ("incident_id", "dedupe_key", "created_at", "execution_id")
        ],
        GlobalSecondaryIndexes=[
            {
                "IndexName": "by_dedupe_key",
                "KeySchema": [
                    {"AttributeName": "dedupe_key", "KeyType": "HASH"},
                    {"AttributeName": "created_at", "KeyType": "RANGE"},
                ],
                "Projection": {"ProjectionType": "ALL"},
            },
            {
                "IndexName": "by_execution_id",
                "KeySchema": [{"AttributeName": "execution_id", "KeyType": "HASH"}],
                "Projection": {"ProjectionType": "ALL"},
            },
        ],
    )


def alarm(name_suffix: str, state: str = "ALARM") -> dict:
    ev = json.loads((FIX / "alarm_unhealthy.json").read_text())
    ev["detail"]["alarmName"] = f"aiops-dev-{name_suffix}"
    ev["detail"]["state"]["value"] = state
    if name_suffix != "unhealthy-targets":
        ev["detail"]["configuration"]["metrics"] = []
    return ev


def approve(rem: RemediationService, incident_id: str, why: str) -> dict:
    resp = rem.handle(
        {
            "requestContext": {"authorizer": {"iam": {"userArn": OPERATOR}}},
            "body": json.dumps({"incident_id": incident_id, "decision": "approve", "justification": why}),
        }
    )
    return json.loads(resp["body"])


def show(store: IncidentStore, incident_id: str) -> None:
    inc = store.get(incident_id)
    a = inc.analysis
    print(f"\n| Field | Value |\n|---|---|\n| Incident | `{inc.incident_id}` |\n| Severity | {inc.severity} |")
    print(f"| Status | {inc.status} |\n| Engine | {a['engine']} (confidence {a['confidence']}) |")
    print(f"| Probable cause | {a['probable_cause']} |\n| Recommended runbook | `{a['recommended_runbook']}` |\n")
    print("History:\n")
    for h in inc.history:
        print(f"- `{h['at']}` **{h['action']}** by `{h['actor'].rsplit('/', 1)[-1]}` - {h['detail'][:140]}")
    print()


def main() -> None:
    print("# LOCAL SIMULATION - not an AWS deployment\n")
    print("Generated by `scripts/local_demo.py`: real platform code, mocked AWS (moto DynamoDB, fake SSM),")
    print("recorded evidence, rules engine (Bedrock disabled). See docs/evidence/README.md for AWS evidence.\n")
    cfg = Config.from_env()
    cfg.cluster, cfg.service = "aiops-dev-cluster", "aiops-dev-app"
    cfg.automation_role_arn = "arn:aws:iam::123456789012:role/aiops-dev-ssm-automation"
    cfg.high_risk_approver_arn = "arn:aws:iam::123456789012:role/aiops-dev-senior-approver"
    cfg.approver_arn_prefixes = ["arn:aws:sts::123456789012:assumed-role/aiops-dev-operator/"]
    with mock_aws():
        store = IncidentStore(make_table())
        rem = RemediationService(cfg, store, FakeSSM(), Quiet())
        status = StatusService(store, Quiet())

        # Scenario A: app stopped (desired count 0) -> SEV1 -> human approves restore -> resolved
        print("## Scenario A - test application stopped (ECS desired count = 0)\n")
        ana = AnalyzerService(
            cfg,
            store,
            RecordedEvidence(
                {
                    "ecs_service": {
                        "desired": 0,
                        "running": 0,
                        "recent_events": ["(service aiops-dev-app) has stopped 1 running tasks"],
                    },
                    "target_health": {"total": 0, "healthy": 0},
                }
            ),
            Quiet(),
        )
        r = ana.handle(alarm("no-healthy-targets"))
        print(f"> analyzer: `{json.dumps(r)}`")
        print(
            f"> approval: `{json.dumps(approve(rem, r['incident_id'], 'Service was scaled to 0 by mistake; restore baseline.'))}`"
        )
        print(
            f"> status: `{json.dumps(status.handle({'detail': {'ExecutionId': 'exec-local-1', 'Status': 'Success'}}))}`"
        )
        show(store, r["incident_id"])

        # Scenario B: unhealthy task -> ECS self-heals -> alarm OK auto-resolves (no human action needed)
        print("## Scenario B - ECS task made unhealthy (/health -> 503)\n")
        ana.collector = RecordedEvidence(
            {
                "ecs_service": {"desired": 1, "running": 1},
                "target_health": {"total": 1, "healthy": 0, "unhealthy_reasons": ["Target.ResponseCodeMismatch"]},
                "recent_errors": ["health check failing: dependency 'orders-db' unreachable (fault injected)"],
            }
        )
        r = ana.handle(alarm("unhealthy-targets"))
        print(f"> analyzer: `{json.dumps(r)}`")
        task = json.loads((FIX / "ecs_task_stopped.json").read_text())
        task["detail"].update(stopCode="ServiceSchedulerInitiated", stoppedReason="Task failed ELB health checks")
        print(f"> analyzer (task stop): `{json.dumps(ana.handle(task))}`  <- correlated, not a new incident")
        print(f"> analyzer (alarm OK): `{json.dumps(ana.handle(alarm('unhealthy-targets', 'OK')))}`")
        show(store, r["incident_id"])

        # Scenario C: 5xx spike -> HIGH risk rollback recommended -> needs 2nd approval in SSM
        print("## Scenario C - HTTP 5xx spike after a deployment (HIGH-risk recommendation)\n")
        ana.collector = RecordedEvidence({"recent_errors": ["Exception: unhandled NullReference in /checkout"]})
        r = ana.handle(alarm("alb-5xx"))
        print(f"> analyzer: `{json.dumps(r)}`")
        print(f"> approval: `{json.dumps(approve(rem, r['incident_id'], 'Errors began with revision 8; roll back.'))}`")
        print("> SSM execution now waits at the `aws:approve` step for the senior-approver role.\n")
        show(store, r["incident_id"])

        print("## Dashboard widget output (HTML rendered by the custom widget Lambda)\n")
        print("```html")
        print(render(store.list_recent())[:1500] + " ...")
        print("```")


if __name__ == "__main__":
    main()
